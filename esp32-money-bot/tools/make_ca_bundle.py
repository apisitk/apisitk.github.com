#!/usr/bin/env python3
"""Build money_bot/ca_bundle.h (ESP-IDF x509 cert bundle) from Mozilla's CA list.

Same format as esp-idf/components/mbedtls/esp_crt_bundle/gen_crt_bundle.py.
Usage: pip install certifi cryptography && python3 tools/make_ca_bundle.py
"""
import os
import struct

import certifi
from cryptography import x509
from cryptography.hazmat.primitives import serialization

OUT = os.path.join(os.path.dirname(__file__), '..', 'money_bot', 'ca_bundle.h')

certs = x509.load_pem_x509_certificates(open(certifi.where(), 'rb').read())
certs.sort(key=lambda c: c.subject.public_bytes())

blob = struct.pack('>H', len(certs))
for c in certs:
    name = c.subject.public_bytes()
    key = c.public_key().public_bytes(serialization.Encoding.DER,
                                      serialization.PublicFormat.SubjectPublicKeyInfo)
    blob += struct.pack('>HH', len(name), len(key)) + name + key

with open(OUT, 'w') as f:
    f.write('// Generated by tools/make_ca_bundle.py from certifi %s (%d roots). Do not edit.\n'
            % (certifi.__version__, len(certs)))
    f.write('#pragma once\n#include <stdint.h>\n#include <stddef.h>\n\n')
    f.write('static const uint8_t CA_BUNDLE[] = {\n')
    for i in range(0, len(blob), 20):
        f.write('  ' + ','.join('0x%02x' % b for b in blob[i:i + 20]) + ',\n')
    f.write('};\nstatic const size_t CA_BUNDLE_LEN = sizeof(CA_BUNDLE);\n')
print('wrote %s: %d roots, %d bytes' % (OUT, len(certs), len(blob)))
